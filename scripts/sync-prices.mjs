// Generate the committed price snapshot from models.dev.
//
//   node scripts/sync-prices.mjs          rewrite shared/price-book.js
//   node scripts/sync-prices.mjs --check  exit 1 when the committed file differs,
//                                         naming each model that moved (exit 2:
//                                         models.dev did not answer)
//
// The service never touches the network: a price change is a release, and this
// script is run by hand when one happens. It is not part of `npm run verify`.
//
// Attribution: rates come from https://models.dev (MIT), filtered to the six
// providers the meter prices. Only public list prices are kept: no credentials,
// no conversation data, no runtime URLs.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { buildPriceBook, PRICE_SOURCE, PROVIDERS } from '../shared/price-book-build.js';
import { diffBooks } from './price-diff.mjs';

const SOURCE = PRICE_SOURCE;
const TIMEOUT_MS = 15_000;
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TARGET = path.join(ROOT, 'shared', 'price-book.js');

function render(book) {
  return [
    '// GENERATED by scripts/sync-prices.mjs — do not edit.',
    `// Source: ${SOURCE}, filtered to ${Object.keys(PROVIDERS).length} providers.`,
    `export const PRICE_BOOK = ${JSON.stringify(book, null, 2)};`,
    '',
  ].join('\n');
}

const today = new Date().toISOString().slice(0, 10);
const check = process.argv.includes('--check');
const existing = (() => {
  try {
    return readFileSync(TARGET, 'utf8');
  } catch (error) {
    if (error.code === 'ENOENT') return null;
    throw error;
  }
})();

// --check must not fail only because a day passed since the snapshot was made.
const checkedAt = check ? (existing?.match(/^ {2}"checkedAt": "([^"]+)",$/m)?.[1] ?? today) : today;

let api;
try {
  const answer = await fetch(SOURCE, { signal: AbortSignal.timeout(TIMEOUT_MS) });
  if (!answer.ok) throw new Error(`HTTP ${answer.status}`);
  api = await answer.json();
} catch (error) {
  console.error(`sync-prices: fetch failed: ${error.message}`);
  process.exit(2);
}

const output = render(buildPriceBook(api, checkedAt));

if (check) {
  if (existing === output) {
    console.log('sync-prices: committed book matches models.dev');
    process.exit(0);
  }
  // Say what moved, not only that something did: a scheduled check is read by
  // a person deciding whether a price change is worth a release.
  const committed = existing ? (await import(pathToFileURL(TARGET).href)).PRICE_BOOK : null;
  const lines = diffBooks(committed, buildPriceBook(api, checkedAt));
  for (const line of lines) console.error(line);
  if (!lines.length) console.error('(no rate, model or tier moved: the file differs in aliases, labels or layout)');
  console.error(`sync-prices: committed book is stale, ${lines.length} model line(s) (run node scripts/sync-prices.mjs)`);
  process.exit(1);
}

if (existing === output) {
  console.log('sync-prices: no change');
  process.exit(0);
}
writeFileSync(TARGET, output);
const totals = Object.entries(JSON.parse(output.slice(output.indexOf('{'), output.lastIndexOf('}') + 1)))
  .filter(([key]) => key === 'providers')
  .flatMap(([, providers]) => Object.entries(providers))
  .map(([id, provider]) => `${id} ${Object.keys(provider.models).length}`)
  .join(', ');
console.log(`sync-prices: wrote shared/price-book.js — ${totals}`);
